"""Markdown-native factories for Bots, Context, Skills, Agents, and Loops.

Factories materialize reviewable Markdown artifacts only. External Hermes side
 effects (profile creation, cron creation, skill installation) are intentionally
 represented by adapter records and require a separate approved executor.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import re

from .model import Proposal


@dataclass(frozen=True)
class Materialized:
    primitive: str
    slug: str
    path: Path


def _safe_slug(value: str) -> str:
    value = re.sub(r"[^a-z0-9-]+", "-", value.lower()).strip("-")
    return value or "untitled"


def _bot_root(root: Path, slug: str) -> Path:
    bot = root / "bots" / _safe_slug(slug)
    for directory in (".system", "skills", "agents", "loops"):
        (bot / directory).mkdir(parents=True, exist_ok=True)
    return bot


def _append(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if text.strip() in existing:
            return
        path.write_text(existing.rstrip() + "\n\n" + text.strip() + "\n", encoding="utf-8")
    else:
        path.write_text(text.strip() + "\n", encoding="utf-8")


def materialize_context(root: str | Path, bot: str, proposals: list[Proposal]) -> Materialized:
    target = _bot_root(Path(root), bot)
    lines = [
        "---", "type: bot", f"slug: {_safe_slug(bot)}", f"name: {bot.title()}",
        "owner: sovthpaw", "status: seeding", "tags: [bot]", "---", "",
        f"# {bot.title()}", "", "> Bot dashboard generated by Senter Agent.", "", "## Evidence",
    ]
    for proposal in proposals:
        lines.append(f"- `{proposal.primitive}:{proposal.slug}` — {proposal.reason}")
    (target / "BOT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return Materialized("bot", _safe_slug(bot), target / "BOT.md")


def materialize_proposal(root: str | Path, bot: str, proposal: Proposal) -> Materialized:
    target = _bot_root(Path(root), bot)
    heading = proposal.slug.replace("-", " ").title()
    if proposal.primitive == "bot":
        path = target / "BOT.md"
        content = (
            "---\n"
            f"type: bot\nslug: {_safe_slug(proposal.slug)}\nname: {heading}\n"
            "owner: sovthpaw\nstatus: seeding\n"
            f"tags: [bot]\n---\n\n# {heading}\n\n"
            f"**Mission.** {proposal.reason}\n\n## Evidence\n\n"
            + "\n".join(f"- `{source}`" for source in proposal.source_documents)
        )
        _append(path, content)
        return Materialized("bot", proposal.slug, path)
    directory = {"skill": "skills", "agent": "agents", "loop": "loops", "context": ".system"}[proposal.primitive]
    suffix = "SKILL.md" if proposal.primitive == "skill" else "README.md"
    path = target / directory / f"{_safe_slug(proposal.slug)}-{suffix}" if suffix != "README.md" else target / directory / f"{_safe_slug(proposal.slug)}.md"
    if proposal.primitive == "skill":
        content = f"---\nname: {_safe_slug(proposal.slug)}\ndescription: {proposal.reason}\n---\n\n# {heading}\n\n## Status\n\nProposed; review before installing.\n\n## Evidence\n\n" + "\n".join(f"- `{source}`" for source in proposal.source_documents)
    else:
        content = f"# {heading}\n\n- **Primitive:** `{proposal.primitive}`\n- **Status:** proposed\n- **Reason:** {proposal.reason}\n\n## Evidence\n" + "\n".join(f"- `{source}`" for source in proposal.source_documents)
    _append(path, content)
    return Materialized(proposal.primitive, proposal.slug, path)


def materialize_all(root: str | Path, bot: str, proposals: list[Proposal]) -> list[Materialized]:
    """Materialize every reviewed proposal as editable Markdown inside one bot."""
    result = [materialize_context(root, bot, proposals)]
    result.extend(materialize_proposal(root, bot, proposal) for proposal in proposals)
    return result


__all__ = ["Materialized", "materialize_all", "materialize_context", "materialize_proposal"]
